const texts = [...document.querySelectorAll('[data-i18n]')];
const labels = [...document.querySelectorAll('[data-i18n-label]')];
const waLinks = [...document.querySelectorAll('[data-i18n-wa]')];

// Capture the English copy from the page so it stays the single source for English.
const en = { title: document.title };
texts.forEach((el) => { en[el.dataset.i18n] = el.textContent; });
labels.forEach((el) => { en[el.dataset.i18nLabel] = el.getAttribute('aria-label') || el.title; });
waLinks.forEach((a) => { en[a.dataset.i18nWa] = new URL(a.href).searchParams.get('text'); });

function setLang(lang) {
  const t = I18N[lang] || {};
  const get = (key) => t[key] ?? en[key];
  document.documentElement.lang = lang === 'en' ? 'en-IN' : lang;
  document.title = get('title');
  texts.forEach((el) => { el.textContent = get(el.dataset.i18n); });
  labels.forEach((el) => { el.setAttribute('aria-label', get(el.dataset.i18nLabel)); });
  waLinks.forEach((a) => { a.href = a.href.split('?')[0] + '?text=' + encodeURIComponent(get(a.dataset.i18nWa)); });
}

const picker = document.getElementById('lang');
const valid = (lang) => lang === 'en' || lang in I18N;
let saved = null;
try { saved = localStorage.getItem('lang'); } catch {}
const fromUrl = new URLSearchParams(location.search).get('lang');
const initial = [fromUrl, saved].find(valid) || 'en';
if (initial !== 'en') setLang(initial);
picker.value = initial;

picker.addEventListener('change', () => {
  const lang = picker.value;
  setLang(lang);
  try { localStorage.setItem('lang', lang); } catch {}
  // Keep the choice in the address bar so a shared link opens in the same language.
  const url = new URL(location.href);
  if (lang === 'en') url.searchParams.delete('lang'); else url.searchParams.set('lang', lang);
  history.replaceState(null, '', url);
});

// Reveal sections as they enter the viewport. Falls back to visible if the
// observer is missing or the visitor prefers reduced motion.
const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
const targets = document.querySelectorAll('.reveal');
if (!reduce && 'IntersectionObserver' in window) {
  const io = new IntersectionObserver((entries) => {
    for (const e of entries) {
      if (e.isIntersecting) { e.target.classList.add('is-in'); io.unobserve(e.target); }
    }
  }, { rootMargin: '0px 0px -10% 0px', threshold: 0.15 });
  targets.forEach((t) => io.observe(t));
} else {
  targets.forEach((t) => t.classList.add('is-in'));
}

document.getElementById('year').textContent = new Date().getFullYear();
